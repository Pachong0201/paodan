# -*- coding: utf-8 -*-
"""治理类核验建议集中维护。

不要在 GovernanceComplaintScorer 内散落 G01/G08/G10 的核验语句。
"""
from __future__ import annotations

from typing import Dict, Iterable, List

# 每类治理问题的具体核验动作（自然语言，供记者核查清单使用）
VERIFICATION_BY_CATEGORY: Dict[str, List[str]] = {
    "G01": ["核对法定办理期限", "核对案件编号", "核对历次补件通知", "核对1999/陈情回复记录"],
    "G02": ["核对系统错误时间线", "核对线上申请/补件失败截图", "核对系统维护公告与错误码", "核对受影响申请件数"],
    "G03": ["核对原核准/补助核定文件", "核对追缴或要求返还通知", "核对认定错误前后的公文", "核对实际损失金额与凭证"],
    "G04": ["核对社宅/租金补贴申请条件", "核对候补名单与序号", "核对地方政府供给计划", "核对受影响家庭数与等待时间"],
    "G05": ["核对公托/幼儿园缺额公告", "核对候补人数与抽签规则", "核对地方教育/托育预算", "核对受影响家长群体规模"],
    "G06": ["核对急诊检伤分级记录", "核对病床等待时间与转院记录", "核对医院量能与公告", "核对受影响患者人数"],
    "G07": ["核对交通事故/行人事故纪录", "核对道路设计或号志设置", "核对主管机关会勘记录", "核对历次改善承诺"],
    "G08": ["核对台电/水务事故纪录", "核对停供区域", "核对受影响户数", "核对历次抢修时间", "核对损害凭证"],
    "G09": ["核对垃圾清运/市容巡查纪录", "核对1999派工与回复记录", "核对受影响里邻范围", "核对历次会勘与改善期限"],
    "G10": ["核对报案纪录", "核对三联单", "核对受理时间", "核对冻结时间", "核对诈骗资金转移时间线"],
    "G11": ["核对灾害预警发布时间", "核对撤离/通知纪录", "核对受灾范围与淹水纪录", "核对跨局处应变会议纪录"],
    "G12": ["核对中央/地方函释或认定标准", "核对同案不同窗口处理结果", "核对政策宣传与实际执行落差", "核对受影响群体与陈情纪录"],
}

GENERIC_GOVERNANCE_VERIFICATION = [
    "核对事件时间线",
    "核对主管机关与承办单位",
    "核对陈情/投诉/报案纪录",
    "核对受影响群体规模与具体损失",
    "核对原始截图、公文或通知等证据",
]


def verification_targets_for(categories: Iterable[str], limit: int = 12) -> List[str]:
    """按治理类别返回集中维护的核验建议，去重并保序。"""
    out: List[str] = []
    for cid in categories or []:
        cid = str(cid or "").strip().upper()
        for item in VERIFICATION_BY_CATEGORY.get(cid, []):
            if item not in out:
                out.append(item)
    if not out:
        out.extend(GENERIC_GOVERNANCE_VERIFICATION)
    return out[:limit]
